def grade_for(score: float) -> str:
    if score >= 90:
        return "A"
    if score >= 75:
        return "B"
    if score >= 55:
        return "C"
    if score >= 35:
        return "D"
    return "F"


def select_tools(tools: List[Dict[str, Any]], selector: str) -> List[Dict[str, Any]]:
    """Apply a template's tool selector to a live tools/list."""
    if selector in ("*", "all"):
        return list(tools)
    if selector.startswith("regex:"):
        pattern = selector[len("regex:"):]
        rx = re.compile(pattern)
        return [t for t in tools if rx.search(t.get("name", ""))]
    wanted = {s.strip() for s in selector.split(",") if s.strip()}
    return [t for t in tools if t.get("name") in wanted]
